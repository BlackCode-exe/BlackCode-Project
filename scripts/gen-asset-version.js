// AUTO-RUN before every build (see package.json "build" script).
// Hashes the actual content of assets/css and assets/js so cache-busting
// happens automatically whenever those files change — no manual bump needed.
const fs     = require("fs");
const path   = require("path");
const crypto = require("crypto");

const ROOT = path.join(__dirname, "..");

function collectFiles(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir)
    .filter(f => /\.(css|js)$/.test(f))
    .sort()
    .map(f => path.join(dir, f));
}

const files = [
  ...collectFiles(path.join(ROOT, "assets/css")),
  ...collectFiles(path.join(ROOT, "assets/js")),
];

const hash = crypto.createHash("sha256");
for (const f of files) hash.update(fs.readFileSync(f));
const version = hash.digest("hex").slice(0, 12);

const out = `// AUTO-GENERATED by scripts/gen-asset-version.js on every build — do not edit by hand.
// Derived from a SHA-256 hash of assets/css + assets/js content, so it
// changes automatically whenever those files change instead of needing a
// manual bump.
export const ASSET_VERSION = ${JSON.stringify(version)};
`;

fs.writeFileSync(path.join(ROOT, "src/utils/asset-version.js"), out);
console.log(`Generated ASSET_VERSION: ${version} (from ${files.length} file(s))`);
