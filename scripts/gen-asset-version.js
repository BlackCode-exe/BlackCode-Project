// AUTO-RUN before every build (see package.json "build" script).
// Hashes each asset file's own content individually, so cache-busting is
// per-file: changing styles.css no longer forces every image and script to
// re-fetch too, and updating a logo/favicon now busts its own cache key
// (previously images weren't hashed at all and could go stale indefinitely).
const fs     = require("fs");
const path   = require("path");
const crypto = require("crypto");

const ROOT   = path.join(__dirname, "..");
const ASSETS = path.join(ROOT, "assets");

// Only these extensions are versioned — matches what's actually served with
// a ?v= query string in index.js / shell.js today.
const VERSIONED_EXT = /\.(css|js|png|ico)$/;

function collectFiles(dir, baseDir) {
  const out = [];
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      out.push(...collectFiles(full, baseDir));
    } else if (VERSIONED_EXT.test(entry.name)) {
      out.push(full);
    }
  }
  return out;
}

const files = collectFiles(ASSETS, ASSETS).sort();

const versions = {};
for (const f of files) {
  const relPath = path.relative(ASSETS, f).split(path.sep).join("/"); // e.g. "css/styles.css", "favicon.ico"
  const hash = crypto.createHash("sha256").update(fs.readFileSync(f)).digest("hex").slice(0, 12);
  versions[relPath] = hash;
}

const out = `// AUTO-GENERATED by scripts/gen-asset-version.js on every build — do not edit by hand.
// Per-file SHA-256 hash (first 12 hex chars) of each asset's own content.
// Changing one file only busts that file's own cache key — untouched
// assets keep their existing (fast, cached) version string.
export const ASSET_VERSIONS = ${JSON.stringify(versions, null, 2)};

// Falls back to "0" for any path not in the map (e.g. a new file added to
// assets/ that hasn't been through a build yet) rather than throwing.
export function assetVersion(relPath) {
  return ASSET_VERSIONS[relPath] || "0";
}
`;

fs.writeFileSync(path.join(ROOT, "src/utils/asset-version.js"), out);
console.log(`Generated per-file ASSET_VERSIONS for ${files.length} file(s).`);
